def qc_hr_error(df: pd.DataFrame, dev: str, cond: str, split: str = "all") -> tuple[float, int]:
    """Mean |HR - ECG HR| (bpm) over windows with at least one accepted HRV segment.

    HR is the duration-weighted mean heart rate of the accepted segments.
    """
    g = df[(df["device"] == dev) & (df["condition"] == cond) & (df["n_segments"].fillna(0) > 0)]
    if split != "all":
        g = g[g["split"] == split]
    err = (g["mean_hr"] - g["ecg_hr"]).abs().dropna()
    return (float(err.mean()) if len(err) else np.nan), int(len(err))


