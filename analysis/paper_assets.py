def table_ablation(out: str, results_dir: str) -> None:
    ab = pd.read_csv(os.path.join(results_dir, "ablation_summary.csv"))
    names = [("no_beat_recovery", "No beat recovery"), ("recovered_in_differences", "Recovered beats in differences"),
             ("no_timing_refinement", "No wide-band timing"), ("no_sqi", "No beat SQI screen"),
             ("sqi_0.70", "SQI threshold 0.70 (both devices)"), ("sqi_0.90", "SQI threshold 0.90"),
             ("no_cadence_gate", "No cadence-lock gate"), ("rhythm_gate", "Add spectral rhythm gate"),
             ("device_hr_gate", "Add device-HR gate"), ("strict", "Strict gates (burden 2\\%, jitter 10\\%)"),
             ("burden_10pct", "Burden limit 10\\%"), ("permissive", "Permissive gates (15\\%, 25\\%)"),
             ("min_segment_60s", "Minimum segment 60 s"), ("neurokit2_only", "NeuroKit2 detector only"),
             ("anc_off", "ANC off"), ("anc_both_devices", "ANC on both devices"), ("anc_all_motion", "ANC in all motion states")]

    def cell(variant, dev, split, metric, d, signed=True):
        r = ab[(ab["variant"] == variant) & (ab["device"] == dev) & (ab["split"] == split) & (ab["condition"] == "rest")]
        b = ab[(ab["variant"] == "base") & (ab["device"] == dev) & (ab["split"] == split) & (ab["condition"] == "rest")]
        if r.empty or b.empty:
            return "--"
        return num(r[metric].iloc[0] - b[metric].iloc[0], d, signed)

    rows = []
    for key, label in names:
        rows.append([label] + [cell(key, dev, sp, mt, d) for dev in DEV for mt, d in (("hrv_yield_pct", 0), ("rmssd_abs_log_error", 3))
                               for sp in ("dev", "test")])
    base = []
    for dev in DEV:
        for mt, d in (("hrv_yield_pct", 0), ("rmssd_abs_log_error", 3)):
            for sp in ("dev", "test"):
                r = ab[(ab["variant"] == "base") & (ab["device"] == dev) & (ab["split"] == sp) & (ab["condition"] == "rest")]
                base.append(num(r[mt].iloc[0], d))
    rows.insert(0, ["\\textit{Reference configuration (absolute)}", *base])
    write_table(out, "lrrrrrrrr",
                ["", "\\multicolumn{4}{c}{Empatica E4}", "\\multicolumn{4}{c}{Galaxy Watch 5}"],
                rows, midrules=[1],
                header2=["Variant", "Yield dev", "Yield test", "Err dev", "Err test",
                         "Yield dev", "Yield test", "Err dev", "Err test"])


def table_consistency(out: str, m_df: pd.DataFrame, tables: dict) -> None:
    """Dev vs test for the headline seated-rest results."""
    ppg = m_df[m_df["device"].isin(DEV)]
    hrv = tables["hrv_agreement"]
    hr = tables["hr_agreement"]
    rows = []
    items = [("HR MAE (bpm)", "hr"), ("Beat F1, median (\\%)", "f1"), ("IBI MAE, median (ms)", "ibi"),
             ("HRV yield (\\%)", "yield"), ("RMSSD ratio (GM)", "rmssd"), ("SDNN ratio (GM)", "sdnn")]
    for label, key in items:
        row = [label]
        for dev in DEV:
            for sp in ("dev", "test"):
                g = ppg[(ppg["device"] == dev) & (ppg["condition"] == "rest") & (ppg["split"] == sp)]
                if key == "hr":
                    v = hr[(hr["device"] == dev) & (hr["condition"] == "rest") & (hr["split"] == sp)]["mae_bpm"].iloc[0]
                    row.append(num(v, 2))
                elif key == "f1":
                    row.append(num(g["f1_vs_ecg"].median(), 1))
                elif key == "ibi":
                    row.append(num(g["beat_ibi_mae_vs_ecg"].median(), 1))
                elif key == "yield":
                    row.append(num(100 * (g["n_segments"].fillna(0) > 0).mean(), 0))
                else:
                    v = hrv[(hrv["device"] == dev) & (hrv["condition"] == "rest") & (hrv["metric"] == key) & (hrv["split"] == sp)]
                    row.append(num(v["ratio"].iloc[0], 2))
        rows.append(row)
    write_table(out, "lrrrr", ["Quantity (seated rest)", "\\multicolumn{2}{c}{Empatica E4}",
                               "\\multicolumn{2}{c}{Galaxy Watch 5}"], rows,
                header2=["", "dev", "test", "dev", "test"], cmidrules="\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}")


def table_params(out: str, df: pd.DataFrame, config: dict) -> None:
    """Device parameters, read from the configuration and the measured sampling rates."""
    dev = config["devices"]

    def band(name: str) -> str:
        low, high = dev[name]["bandpass"]
        return f"{low:g}--{high:g}, {dev[name]['filter_order']}"

    def thr(name: str) -> str:
        t = dev[name]["motion_thresholds"]
        return f"{t['moderate']:.2f} / {t['severe']:.2f}"

    def fs(name: str) -> str:
        measured = df[df["device"] == name]["fs_effective"].median()
        return f"{dev[name]['fs']} / {measured:.2f}"

    sqi = {k: dev[k].get("sqi_beat_threshold") for k in dev}
    timing = config["processing"]["timing"]["highcut_hz"]
    anc = config["processing"]["anc"]
    rows = [
        ["Motion thresholds $\\theta_{\\mathrm{mod}}/\\theta_{\\mathrm{sev}}$ (g)", thr("E4"), thr("GalaxyWatch"), thr("PolarH10")],
        ["Detection band-pass (Hz), order per edge", band("E4"), band("GalaxyWatch"), band("PolarH10")],
        ["Timing band-pass, upper cut-off (Hz)", f"{timing['E4']:g}", f"{timing['GalaxyWatch']:g}", "--"],
        ["Fixed polarity (systolic up)", f"{dev['E4']['polarity']:+d}".replace("-", "$-$"),
         f"{dev['GalaxyWatch']['polarity']:+d}".replace("-", "$-$"), "--"],
        ["Beat-quality threshold $\\rho_{\\min}$", *(f"{sqi[k]:.2f}" if sqi[k] is not None else "none" for k in dev)],
        [f"Noise cancellation (NLMS, order {anc['order']})",
         "moderate, severe" if "E4" in anc["devices"] else "off",
         "moderate, severe" if "GalaxyWatch" in anc["devices"] else "off", "off"],
        ["Sampling rate: nominal / fitted (Hz)", fs("E4"), fs("GalaxyWatch"), fs("PolarH10")],
    ]
    write_table(out, "lccc", ["Parameter", "Empatica E4", "Galaxy Watch 5", "Polar H10"], rows)


def copy_figures(fig_dir: str, paper_fig: str) -> None:
    os.makedirs(paper_fig, exist_ok=True)
    for name in sorted(os.listdir(fig_dir)):
        if name.endswith((".eps", ".png")) and name.startswith("fig"):
            shutil.copy2(os.path.join(fig_dir, name), os.path.join(paper_fig, name))


def package_version(package: str | None) -> str:
    """Installed version of a package (``None``: the Python interpreter, major.minor only)."""
    import sys
    from importlib import metadata

    version = ".".join(map(str, sys.version_info[:3])) if package is None else metadata.version(package)
    return ".".join(version.split(".")[:3 if package else 2])


def count_tests() -> int | None:
    """Number of collected pytest tests (so that the manuscript never carries a hand-typed count)."""
    import re
    import subprocess
    import sys

    try:
        proc = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:warnings", "tests"],
                              capture_output=True, text=True, timeout=300, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    text = proc.stdout + proc.stderr
    found = re.search(r"(\d+) tests? collected", text)
    if found:
        return int(found.group(1))
    per_file = re.findall(r"^tests/\S+\.py: (\d+)$", text, flags=re.M)  # newer pytest prints per-file counts
    return sum(int(n) for n in per_file) if per_file else None


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate manuscript numbers and tables")
    parser.add_argument("--paper-dir", required=True)
    parser.add_argument("--results-dir", default="paper_results")
    parser.add_argument("--fig-dir", default="fig")
    parser.add_argument("--config", default="config.yaml")
    args = parser.parse_args()

    out = os.path.join(args.paper_dir, "generated")
    os.makedirs(out, exist_ok=True)
    df = load_combined(os.path.join(args.results_dir, "combined_results.csv"))
    tdir = os.path.join(args.results_dir, "tables")
    tables = {n[:-4]: pd.read_csv(os.path.join(tdir, n)) for n in os.listdir(tdir) if n.endswith(".csv")}
    with open(os.path.join(args.results_dir, "cache", "beats.pkl"), "rb") as handle:
        cache = pickle.load(handle)["participants"]

    macros = Macros()
    main_macros(macros, df, tables)
    beat_ibi_macros(macros, cache)
    timing_error_macros(macros, cache, df)
    study_macros(macros, args.results_dir)
    macros.add("TestCount", count_tests(), digits=None)
    for name, package in (("Python", None), ("Numpy", "numpy"), ("Scipy", "scipy"), ("Pandas", "pandas"),
                          ("Neurokit", "neurokit2"), ("Heartpy", "heartpy")):
        macros.add("Ver" + name, package_version(package))
    macros.write(os.path.join(out, "numbers.tex"))

    table_sessions(os.path.join(out, "tab_sessions.tex"), df)
    table_params(os.path.join(out, "tab_params.tex"), df, load_config(os.path.join(args.config)))
    table_hr(os.path.join(out, "tab_hr.tex"), tables, df)
    table_beats(os.path.join(out, "tab_beats.tex"), df)
    table_hrv_rest(os.path.join(out, "tab_hrv_rest.tex"), tables)
    table_hrv_conditions(os.path.join(out, "tab_hrv_conditions.tex"), tables)
    table_baselines(os.path.join(out, "tab_baselines.tex"), args.results_dir)
    table_baselines_rmssd(os.path.join(out, "tab_baselines_rmssd.tex"), args.results_dir)
    table_ablation(os.path.join(out, "tab_ablation.tex"), args.results_dir)
    table_consistency(os.path.join(out, "tab_consistency.tex"), df, tables)
    copy_figures(args.fig_dir, os.path.join(args.paper_dir, "fig"))
    print(f"{len(macros.items)} macros written to {out}")


if __name__ == "__main__":
    main()
