class Macros:
    """Collects ``\\newcommand`` definitions."""

    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, name: str, value, digits: int | None = 2, signed: bool = False) -> None:
        if isinstance(value, str):
            text = value
        elif value is None or (isinstance(value, float | np.floating) and not np.isfinite(value)):
            text = "--"
        elif isinstance(value, bool | np.bool_):
            text = "yes" if value else "no"
        elif digits is None or isinstance(value, int | np.integer):
            text = f"{int(value):,}".replace(",", "{,}") if abs(value) >= 10000 else f"{int(value)}"
        else:
            text = f"{float(value):+.{digits}f}" if signed else f"{float(value):.{digits}f}"
            text = _safe_sign(text)
        self.items["num" + name] = text

    def add_p(self, name: str, p: float) -> None:
        """P value including its operator: ``p<0.001`` or ``p=0.070``."""
        if p is None or not np.isfinite(p):
            self.items["num" + name] = "--"
        elif p < 0.001:
            self.items["num" + name] = "\\ensuremath{p<0.001}"
        else:
            self.items["num" + name] = f"\\ensuremath{{p={p:.3f}}}"

    def write(self, path: str) -> None:
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("% Auto-generated by analysis/paper_assets.py - do not edit.\n")
            for name in sorted(self.items):
                handle.write(f"\\newcommand{{\\{name}}}{{{self.items[name]}}}\n")


def _safe_sign(text: str) -> str:
    """Leading +/- as math symbols that work in text and in math mode."""
    if text.startswith("-"):
        return "\\ensuremath{-}" + text[1:]
    if text.startswith("+"):
        return "\\ensuremath{+}" + text[1:]
    return text


def num(x, d=2, signed=False) -> str:
    if x is None or (isinstance(x, float | np.floating) and not np.isfinite(x)):
        return "--"
    text = f"{float(x):+.{d}f}" if signed else f"{float(x):.{d}f}"
    return _safe_sign(text)


def ci(lo, hi, d=2) -> str:
    return f"[{num(lo, d)}, {num(hi, d)}]"


def write_table(path: str, spec: str, header: list[str], rows: list[list[str]], midrules: list[int] | None = None,
                header2: list[str] | None = None, colsep_pt: float | None = None,
                cmidrules: str | None = None) -> None:
    """Write a booktabs table. ``header2`` is a second header row (units); ``colsep_pt`` tightens the column
    padding so that wide tables need less down-scaling in the manuscript."""
    lines = [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", " & ".join(header) + " \\\\"]
    if colsep_pt is not None:
        lines.insert(0, f"\\setlength{{\\tabcolsep}}{{{colsep_pt:g}pt}}")
    if cmidrules:
        lines.append(cmidrules)
    if header2:
        lines.append(" & ".join(header2) + " \\\\")
    lines.append("\\midrule")
    for i, row in enumerate(rows):
        if midrules and i in midrules:
            lines.append("\\midrule")
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


