def ppg_polar_fs(df: pd.DataFrame) -> float:
    """Median fitted sampling rate of the Polar H10 ECG windows."""
    return float(df[df["device"] == "PolarH10"]["fs_effective"].median())


def rest_f1_median(ppg: pd.DataFrame, dev: str) -> float:
    """Median beat F1 of the seated-rest windows of one device."""
    return float(ppg[(ppg["device"] == dev) & (ppg["condition"] == "rest")]["f1_vs_ecg"].median())


