def beat_ibi_macros(m: Macros, cache: dict) -> None:
    """Repeated-measures Bland-Altman of beat-to-beat IBI at rest, from the beat cache."""
    for dev, c in DEV.items():
        ref, det, subj = [], [], []
        for participant, data in cache.items():
            for (d, activity), w in data["windows"].items():
                if d != dev or ACTIVITY_CONDITION.get(activity) != "rest" or not w.get("hrv_ibi"):
                    continue
                ref.append(w["hrv_ibi"]["ibi_reference"])
                det.append(w["hrv_ibi"]["ibi_detected"])
                subj.append(np.full(len(w["hrv_ibi"]["ibi_reference"]), participant))
        ref, det, subj = np.concatenate(ref), np.concatenate(det), np.concatenate(subj)
        ba = bland_altman(det, ref, subj)
        m.add(f"{c}IbiBeats", int(len(ref)), None)
        m.add(f"{c}IbiBias", ba["bias"], 1, signed=True)
        m.add(f"{c}IbiLoALo", ba["loa_low"], 0, signed=True)
        m.add(f"{c}IbiLoAHi", ba["loa_high"], 0, signed=True)
        m.add(f"{c}IbiMaeBeats", float(np.mean(np.abs(det - ref))), 1)
        m.add(f"{c}IbiSd", ba["sd"], 1)
        m.add(f"{c}IbiR", float(np.corrcoef(det, ref)[0, 1]), 3)
        m.add(f"{c}IbiWithinTwenty", 100 * float(np.mean(np.abs(det - ref) <= 20)), 0)

    # tolerance curves (Fig. 3)
    for group, conds in (("Rest", {"rest"}), ("Loco", {"locomotion"})):
        for dev, c in DEV.items():
            vals = {k: {100: [], 500: []} for k in ("aligned", "unaligned", "chance")}
            for data in cache.values():
                for (d, activity), w in data["windows"].items():
                    if d != dev or ACTIVITY_CONDITION.get(activity) not in conds or len(w["detected_s"]) < 10:
                        continue
                    det, ecg, lag = w["detected_s"], w["ecg_s"], w["lag_s"]
                    half = 0.5 * np.median(np.diff(det))
                    for kind, dd, lg in (("aligned", det, lag), ("unaligned", det, 0.0), ("chance", det + half, lag)):
                        for tol in (100, 500):
                            vals[kind][tol].append(match_peaks(ecg, dd, tol / 1000.0, lg)["recall"])
            m.add(f"{c}PmrGap{group}", float(np.mean(vals["unaligned"][500]) - np.mean(vals["chance"][500])), 0)
            for kind, name in (("aligned", "Aligned"), ("unaligned", "Unaligned"), ("chance", "ChanceTol")):
                for tol, tname in ((100, "Hundred"), (500, "FiveHundred")):
                    m.add(f"{c}{name}{tname}{group}", float(np.mean(vals[kind][tol])), 0)


def timing_error_macros(m: Macros, cache: dict, df: pd.DataFrame) -> None:
    """Beat-timing error structure at seated rest (decomposition of the RMSSD inflation)."""
    from analysis.timing_error import cache_timing_errors

    t = cache_timing_errors(cache, df)
    t = t[(t["condition"] == "rest") & (t["n_beats"] >= 30) & (t["n_segments"].fillna(0) > 0)]
    for dev, c in DEV.items():
        g = t[t["device"] == dev]
        m.add(f"{c}ErrN", int(len(g)), None)
        m.add(f"{c}ErrSigma", g["sigma_ms"].median(), 1)
        m.add(f"{c}ErrRho", g["rho1"].median(), 2)
        m.add(f"{c}ErrEps", g["eps_rmssd_ms"].median(), 1)
        m.add(f"{c}ErrWhite", g["whiteness"].median(), 2)
        h = g.dropna(subset=["rmssd", "ecg_rmssd", "eps_rmssd_ms"])
        h = h[(h["rmssd"] > 0) & (h["ecg_rmssd"] > 0)]
        predicted = np.sqrt(1.0 + h["eps_rmssd_ms"] ** 2 / h["ecg_rmssd"] ** 2)
        observed = h["rmssd"] / h["ecg_rmssd"]
        m.add(f"{c}ErrPredRatio", float(np.exp(np.log(predicted).mean())), 2)
        m.add(f"{c}ErrObsRatio", float(np.exp(np.log(observed).mean())), 2)
        excess = (h["rmssd"] ** 2 - h["ecg_rmssd"] ** 2).sum()
        m.add(f"{c}ErrExplained", 100.0 * float((h["eps_rmssd_ms"] ** 2).sum() / excess) if excess > 0 else np.nan, 0)
        m.add(f"{c}ErrEcgRmssd", h["ecg_rmssd"].median(), 1)


